export function resolveLang(settingLang = "auto") {
  if (settingLang === "ru" || settingLang === "en") return settingLang;
  const uiLang =
    globalThis.chrome?.i18n?.getUILanguage?.() ||
    globalThis.navigator?.language ||
    "en";
  return String(uiLang).toLowerCase().startsWith("ru") ? "ru" : "en";
}

export function t(lang, key, params = {}) {
  const dict = MESSAGES[lang === "ru" ? "ru" : "en"] || MESSAGES.en;
  let template = dict[key] ?? MESSAGES.en[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    template = template.replaceAll(`{${k}}`, String(v ?? ""));
  }
  return template;
}

export function getMessagesForLang(lang) {
  return MESSAGES[lang === "ru" ? "ru" : "en"] || MESSAGES.en;
}
